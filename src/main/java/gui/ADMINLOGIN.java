   private String loadAdminHash(String adminId) {
        try (java.sql.Connection con = DBConnection.getConnection();
             java.sql.PreparedStatement ps = con.prepareStatement(
                 "SELECT password_hash FROM admin_account WHERE admin_id = ?")) {
            ps.setString(1, adminId);
            try (java.sql.ResultSet rs = ps.executeQuery()) {
                if (rs.next()) return rs.getString("password_hash");
            }
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(),
                "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
        return null;
    }

    
    private boolean setNewAdminPassword(String adminId) {
        javax.swing.JPasswordField p1 = new javax.swing.JPasswordField(16);
        javax.swing.JPasswordField p2 = new javax.swing.JPasswordField(16);
        javax.swing.JPanel panel = new javax.swing.JPanel(new java.awt.GridLayout(0, 1, 0, 6));
        panel.add(new javax.swing.JLabel("First login: choose a new admin password"));
        panel.add(new javax.swing.JLabel("(at least 6 characters)"));
        panel.add(p1);
        panel.add(new javax.swing.JLabel("Type it again:"));
        panel.add(p2);
 
        while (true) {
            int ok = javax.swing.JOptionPane.showConfirmDialog(this, panel, "New Admin Password",
                    javax.swing.JOptionPane.OK_CANCEL_OPTION, javax.swing.JOptionPane.PLAIN_MESSAGE);
            if (ok != javax.swing.JOptionPane.OK_OPTION) return false;
 
            String a = new String(p1.getPassword());
            String b = new String(p2.getPassword());
            String problem = null;
            if (a.length() < 6) problem = "The password must be at least 6 characters.";
            else if (!a.equals(b)) problem = "The two passwords do not match.";
            else if (a.equals(ADMIN_PASSWORD)) problem = "Choose a password different from the built-in one.";
            if (problem != null) {
                javax.swing.JOptionPane.showMessageDialog(this, problem);
                continue;
            }
 
            try (java.sql.Connection con = DBConnection.getConnection();
                 java.sql.PreparedStatement ps = con.prepareStatement(
                     "INSERT INTO admin_account (admin_id, password_hash) VALUES (?, ?) "
                   + "ON DUPLICATE KEY UPDATE password_hash = VALUES(password_hash)")) {
                ps.setString(1, adminId);
                ps.setString(2, PasswordUtil.hash(p1.getPassword()));
                ps.executeUpdate();
                return true;
            } catch (java.sql.SQLException e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Could not save the password: " + e.getMessage(),
                    "Database Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                return false;
            }
        }
    }

