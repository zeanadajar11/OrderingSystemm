    private void updateChange() {
        try {
        cash = Double.parseDouble(txtCash.getText().trim());
    } catch (NumberFormatException e) {
        cash = 0;
        txtChange.setText("P0.00");
        btnProceed.setEnabled(false);
        return;
    }
 
    if (Double.isNaN(cash) || Double.isInfinite(cash)) {   
        cash = 0;
        txtChange.setText("P0.00");
        btnProceed.setEnabled(false);
        return;
    }
 
    if (Math.round(cash * 100) < Math.round(total * 100)) {
        txtChange.setText("Insufficient");
        btnProceed.setEnabled(false);
    } else {
        change = (Math.round(cash * 100) - Math.round(total * 100)) / 100.0;
        txtChange.setText(String.format("P%.2f", change));
        btnProceed.setEnabled(true);
    }
    }

