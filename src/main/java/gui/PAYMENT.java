    private void btnProceedActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProceedActionPerformed
          Object[] modes = {"DINE-IN", "TAKEOUT", "BACK"};
    int pick = javax.swing.JOptionPane.showOptionDialog(this,
        "Is this order DINE-IN or TAKEOUT?", "Order Type",
        javax.swing.JOptionPane.DEFAULT_OPTION, javax.swing.JOptionPane.QUESTION_MESSAGE,
        null, modes, modes[0]);
    if (pick != 0 && pick != 1) return;          // BACK or closed: nothing is saved
    String orderType = (pick == 0) ? "DINE-IN" : "TAKEOUT";
 
    CHECKOUT checkout = new CHECKOUT();
    boolean saved = checkout.loadReceipt(orderModel, String.format("%.2f", total), cash, change, orderType);
 
    if (!saved) {
        checkout.dispose();   // error dialog already shown; order stays intact
        return;
    }
 
    checkout.setVisible(true);
    parentForm.completeOrder();   // clears the order in WOW
    dispose();
    javax.swing.SwingUtilities.invokeLater(checkout::toFront);
// TODO add your handling code here:
    }//GEN-LAST:event_btnProceedActionPerformed

