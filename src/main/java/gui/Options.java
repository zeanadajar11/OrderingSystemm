    private void loadPicture(javax.swing.JLabel label, String path, int w, int h) {
        java.awt.Image raw = null;
        java.net.URL url = getClass().getResource(path);
        if (url != null) {
            raw = new javax.swing.ImageIcon(url).getImage();
        } else {
            String name = path.substring(path.lastIndexOf('/') + 1);
            String[] tryFiles = {"src/images/" + name, "src/gui/images/" + name, "images/" + name};
            for (String f : tryFiles) {
                java.io.File file = new java.io.File(f);
                if (file.exists()) {
                    raw = new javax.swing.ImageIcon(file.getAbsolutePath()).getImage();
                    break;
                }
            }
        }
        if (raw == null) {
            label.setText("Not found. Working folder: " + new java.io.File(".").getAbsolutePath());
            return;
        }
        label.setIcon(new javax.swing.ImageIcon(raw.getScaledInstance(w, h, java.awt.Image.SCALE_SMOOTH)));
    }

